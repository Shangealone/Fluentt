"""Bounded deterministic schedule-divergence experiment, never learning efficacy."""
import argparse
import csv
import hashlib
import json
from collections import defaultdict
from datetime import date, datetime, timedelta
from decimal import Decimal
from pathlib import Path
from zoneinfo import ZoneInfo

from app.modules.spaced_repetition.fsrs6 import calculate_fsrs6, calculate_retrievability, FSRS6_DEFAULT_PARAMETERS
from app.modules.research.classroom_schemas import calendar_month_boundary
from .prototype import (BaseProposal, CalendarPolicy, EventContext, actionable, candidate, decide,
                        decision_log, frozen, replay_log)

VERSION = "SIMULATED-esr-phase1-grid-v1"
PATTERNS = {
    "cold": (),
    "recent": ((-1,"good"),),
    "mature": ((-30,"good"),(-15,"good"),(-7,"hard"),(-1,"good")),
    "lapsed": ((-14,"good"),(-7,"again"),(-1,"good")),
}
ZONE = ZoneInfo("Asia/Manila")
OPEN = datetime(2026,11,2,tzinfo=ZONE)
CLOSE = calendar_month_boundary(OPEN,1,"Asia/Manila")  # Reuse the real draft's month arithmetic.
POLICIES = (
    CalendarPolicy("engine-calendar-no-weekday-gate",tuple(range(7)),OPEN,datetime(2127,1,1,tzinfo=ZONE)),
    CalendarPolicy("SIMULATED-month-window-all-days",tuple(range(7)),OPEN,CLOSE),
    CalendarPolicy("SIMULATED-proposal-mon-fri",(0,1,2,3,4),OPEN,CLOSE),
    CalendarPolicy("SIMULATED-instructor-friday-only",(4,),OPEN,CLOSE),
    CalendarPolicy("SIMULATED-mon-fri-missed-nov09",(0,1,2,3,4),OPEN,CLOSE,
                   skipped_dates=(date(2026,11,9),)),
)


def scenarios(weekdays=tuple(range(7)), patterns=tuple(PATTERNS), lateness=(0,2,7), deltas=(-.5,-.1,0,.1,.5)):
    """Paired one-step snapshots: same history/response, alternative SIMULATED pK.

    Current responses are scripted, not generated by the hypothetical scheduler.
    This cannot estimate exposure effects, retention or longitudinal efficacy.
    """
    for day in weekdays:
        planned = OPEN + timedelta(days=day,hours=9)
        for history_name in patterns:
            old = None
            for offset,rating in PATTERNS[history_name]:
                old = calculate_fsrs6(old,rating,planned+timedelta(days=offset)).resulting_state
            for late in lateness:
                response_at = planned+timedelta(days=late)
                prediction_at = response_at-timedelta(seconds=3)
                p_f = None
                if old:
                    elapsed=(prediction_at-datetime.fromisoformat(old['last_reviewed_at'])).total_seconds()/86400
                    p_f=calculate_retrievability(elapsed,old['stability'],FSRS6_DEFAULT_PARAMETERS[20])
                for rating in ("again","hard","good","easy"):
                    base_decision=calculate_fsrs6(old,rating,response_at)
                    days=int(base_decision.resulting_interval_seconds/Decimal(86400))
                    base=BaseProposal(response_at,days,base_decision.due_at)
                    for delta in deltas:
                        case_id=f"SIM-d{day}-{history_name}-late{late}-{rating}-delta{delta}"
                        context=EventContext(case_id,'SIM-learner','SIM-item',prediction_at,response_at,old is not None)
                        k=None if p_f is None else max(0.0,min(1.0,p_f+delta))
                        f_snapshot=frozen(context,p_f,"fsrs-6-reference-v1") if p_f is not None else None
                        k_snapshot=frozen(context,k) if k is not None else None
                        shadow=decide(base,context,k_snapshot,f_snapshot)
                        for policy in POLICIES:
                            log=decision_log(context,shadow,policy)
                            assert replay_log(log), 'Synthetic log must reconstruct every decision'
                            base_action=actionable(base.due_at,policy)
                            adjusted_action=actionable(shadow.due_at,policy)
                            comparable=base_action is not None and adjusted_action is not None
                            log.update({
                                'case_id':case_id,'history_kind':history_name,'rating_SIMULATED':rating,
                                'planned_response_at':planned.isoformat(),'late_calendar_days_SIMULATED':late,
                                'starting_weekday':day,'off_weekday_start':day>=5,'delta_requested_SIMULATED':str(delta),
                                'base_actionable_at':base_action.isoformat() if base_action else None,
                                'raw_interval_changed':shadow.raw_interval_days!=base.interval_days,
                                'rounded_interval_changed':shadow.interval_days!=base.interval_days,
                                'both_actionable':comparable,
                                'actionable_day_changed':comparable and base_action.date()!=adjusted_action.date(),
                                'actionable_timestamp_changed':comparable and base_action!=adjusted_action,
                                'availability_changed':(base_action is None)!=(adjusted_action is None),
                                'both_outside_window':base_action is None and adjusted_action is None,
                            })
                            yield log


def summary(rows):
    groups=defaultdict(list)
    for row in rows:
        groups[(row['calendar']['version'],'all_starts')].append(row)
        if not row['off_weekday_start']:
            groups[(row['calendar']['version'],'weekday_starts_only')].append(row)
    result=[]
    for (policy,scope),group in sorted(groups.items()):
        n=len(group);comparable=sum(row['both_actionable'] for row in group)
        counts={key:sum(bool(row[key]) for row in group) for key in [
            'raw_interval_changed','rounded_interval_changed','actionable_day_changed',
            'actionable_timestamp_changed','availability_changed','both_outside_window']}
        result.append({'policy':policy,'scope':scope,'rows':n,'comparable_both_actionable':comparable,
            'fallbacks':sum(row['fallback_reason'] is not None for row in group),**counts,
            'day_divergence_percent_of_all_rows':round(100*counts['actionable_day_changed']/n,4),
            'day_divergence_percent_of_comparable_rows':round(100*counts['actionable_day_changed']/comparable,4) if comparable else None,
            'raw_changes_collapsed_by_rounding':sum(row['raw_interval_changed'] and not row['rounded_interval_changed'] for row in group),
            'rounded_changes_collapsed_to_same_actionable_day':sum(row['rounded_interval_changed'] and row['both_actionable'] and not row['actionable_day_changed'] for row in group)})
    return result


def write_outputs(directory: Path):
    if directory.exists():
        raise FileExistsError("Refuse to overwrite an existing research output directory")
    directory.mkdir(parents=True)
    rows=list(scenarios())
    assert len(rows)==8400, 'Frozen bounded grid changed; version and review it explicitly'
    columns=['evidence_type','case_id','history_kind','rating_SIMULATED','starting_weekday','off_weekday_start',
             'late_calendar_days_SIMULATED','delta_requested_SIMULATED','p_f','p_k','fsrs_interval_days','factor',
             'raw_interval_days','interval_days','base_due_at','due_at','base_actionable_at','actionable_at',
             'fallback_reason','raw_interval_changed','rounded_interval_changed','both_actionable',
             'actionable_day_changed','availability_changed']
    with (directory/'schedules.csv').open('w',encoding='utf-8',newline='') as stream:
        writer=csv.DictWriter(stream,fieldnames=columns+['calendar_version'],extrasaction='ignore')
        writer.writeheader()
        for row in rows:writer.writerow(row|{'calendar_version':row['calendar']['version']})
    with (directory/'decision-logs.jsonl').open('w',encoding='utf-8',newline='\n') as stream:
        for row in rows:stream.write(json.dumps(row,sort_keys=True,separators=(',',':'))+'\n')
    details={
        'evidence_type':'SYNTHETIC SIMULATION RESULTS','simulated':True,'version':VERSION,
        'formula':'I_FSRS * clip(1 + 0.5 * (p_K - p_F), 0.75, 1.25)',
        'interpretation':'Paired scheduling divergence only; no trained FIFAKT or learner retention evidence',
        'unique_snapshot_scenarios':1680,'calendar_policies':5,'rows':len(rows),
        'generation':'Exhaustive deterministic grid, no RNG, seven starting days; weekend starts are sensitivity cases',
        'lateness_days':[0,2,7],'simulated_pK_requested_offsets':[-.5,-.1,0,.1,.5],
        'cold_start':'Unchanged FSRS fallback; no invented cold-start probability',
        'actionability':'Only engine-calendar is current elapsed-time behavior; other calendars are explicit hypothetical projections',
        'instructor_and_missed_day_policy':'Not implemented/approved in live application; stress scenarios only',
        'retention_effect':None,'trained_fifakt_accuracy':None,'logging_replay_passed':len(rows),
        'summaries':summary(rows),
    }
    api=Path(__file__).resolve().parents[2]
    details['source_sha256']={name:hashlib.sha256((api/name).read_bytes()).hexdigest() for name in [
        'app/modules/spaced_repetition/fsrs6.py','ml/esr_phase1/prototype.py','ml/esr_phase1/simulate.py']}
    (directory/'summary.json').write_text(json.dumps(details,indent=2,sort_keys=True)+'\n',encoding='utf-8')
    manifest={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in directory.iterdir() if p.is_file()}
    (directory/'sha256.json').write_text(json.dumps(manifest,indent=2,sort_keys=True)+'\n',encoding='utf-8')
    return details


if __name__=='__main__':
    parser=argparse.ArgumentParser(description='SIMULATED schedule-divergence experiment; no training or database writes')
    parser.add_argument('--output-dir',type=Path,required=True)
    args=parser.parse_args()
    report=write_outputs(args.output_dir)
    print(json.dumps({'evidence_type':report['evidence_type'],'rows':report['rows'],'unique_snapshots':1680,
                      'summary':str(args.output_dir/'summary.json')}))
